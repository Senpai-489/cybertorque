-- Cyber Torque admin schema

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_name varchar(100) not null unique,
  email varchar(255),
  role varchar(30) not null default 'employee' check (role in ('admin', 'employee')),
  password varchar(255) not null
);

alter table public.users add column if not exists email varchar(255);
update public.users set role = 'employee' where role not in ('admin', 'employee');
alter table public.users drop constraint if exists users_role_check;
alter table public.users add constraint users_role_check check (role in ('admin', 'employee'));

alter table public.users enable row level security;

-- Revoke open public read access on users.
-- Only the service_role (used by server-side admin operations) has access to user credentials.
drop policy if exists "Public users can be read by the admin API" on public.users;
drop policy if exists "Service role has full access to users" on public.users;
create policy "Service role has full access to users"
  on public.users
  for all
  to service_role
  using (true)
  with check (true);

-- Optional secure RPC function to look up a user by username without exposing the entire table
create or replace function public.get_auth_user(p_username text)
returns table (id bigint, user_name varchar, role varchar, password varchar)
language sql
security definer
set search_path = public
as $$
  select id, user_name, role, password
  from public.users
  where user_name = p_username
  limit 1;
$$;

