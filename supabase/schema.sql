create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  slug varchar(160) not null unique,
  brand varchar(100) not null,
  name varchar(160) not null,
  model varchar(160) not null,
  variant varchar(100),
  category varchar(100) not null,
  image text not null,
  hero_image text not null,
  frames text[] not null default '{}',
  horsepower varchar(50) not null,
  acceleration varchar(50) not null,
  engine varchar(100) not null,
  seats varchar(20) not null,
  price varchar(80) not null,
  base_price varchar(80) not null,
  year integer not null default extract(year from now()),
  description text not null default '',
  published boolean not null default true
);

alter table public.vehicles enable row level security;

-- Published vehicles are publicly readable by anyone
drop policy if exists "Published vehicles are publicly readable" on public.vehicles;
create policy "Published vehicles are publicly readable"
  on public.vehicles
  for select
  to anon, authenticated
  using (published = true);

-- Remove insecure public update policy. Admin API uses service_role for modifications.
drop policy if exists "Admin API can update vehicles" on public.vehicles;
drop policy if exists "Admin API can read all vehicles" on public.vehicles;
drop policy if exists "Service role has full access to vehicles" on public.vehicles;

create policy "Service role has full access to vehicles"
  on public.vehicles
  for all
  to service_role
  using (true)
  with check (true);

create index if not exists vehicles_brand_idx on public.vehicles (brand);
create index if not exists vehicles_category_idx on public.vehicles (category);
create index if not exists vehicles_published_idx on public.vehicles (published);

create table if not exists public.vehicle_tracking (
  id bigint generated by default as identity primary key,
  tracking_id varchar(40) not null unique,
  vehicle_id bigint not null references public.vehicles(id) on delete cascade,
  status varchar(40) not null default 'Order received' check (status in ('Order received', 'Preparing vehicle', 'In transit', 'Ready for collection', 'Completed')),
  location varchar(160) not null default '',
  estimated_delivery date,
  notes text not null default '',
  updated_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.vehicle_tracking enable row level security;
drop policy if exists "Public tracking lookup" on public.vehicle_tracking;
create policy "Public tracking lookup" on public.vehicle_tracking
  for select to anon, authenticated using (true);
drop policy if exists "Service role has full access to tracking" on public.vehicle_tracking;
create policy "Service role has full access to tracking" on public.vehicle_tracking
  for all to service_role using (true) with check (true);

create index if not exists vehicle_tracking_vehicle_idx on public.vehicle_tracking (vehicle_id);
create index if not exists vehicle_tracking_status_idx on public.vehicle_tracking (status);